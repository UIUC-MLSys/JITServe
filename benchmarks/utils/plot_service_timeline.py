def parse_service_gain_string(data_str: str) -> Dict[int, List[float]]:
    service_gain = {}
    
    for line in data_str.strip().splitlines():
        parts = line.split()
        
        if len(parts) != 5:
            continue
        
        try:
            time_window = int(float(parts[0]))
            
            # 解析四个增益值
            gains = [
                float(parts[1]),  # Latency
                float(parts[2]),  # Throughput
                float(parts[3]),  # Collective
                float(parts[4])   # Total
            ]
            
            service_gain[time_window] = gains
        except (ValueError, IndexError):
            continue
            
    return service_gain

